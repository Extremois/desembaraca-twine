def verified_source_prefix(data,item):
    if hashlib.sha256(data).hexdigest()!=item['sha256'] or len(data)!=item['size']:
        raise ValueError('Source differs from pinned archive')
    prefix=source_notice_prefix(data)
    if len(prefix)!=item['leading_comment_bytes'] or hashlib.sha256(prefix).hexdigest()!=item['leading_comment_sha256']:
        raise ValueError('Leading comment evidence differs from pinned source')
    return prefix


def runtime_reference_materials(sdk,sources):
    """Preserve historical Go terms without treating a URL as current algorithm provenance."""
    selected=[]
    for name,item in sources.items():
        prefix=verified_source_prefix(sdk[name],item)
        if b'golang.org' not in prefix:continue
        lock=json.loads(audit.bounded(HERE/'licenses/material-source-lock.json',65536))['go_tangent_history']
        if (name!=lock['source_path'] or item['sha256']!=lock['source_sha256']
                or b'https://golang.org/src/math/tan.go' not in prefix):
            raise ValueError('Runtime Go reference requires its own byte-bound history review')
        data,origin=license_material('go_1_17_license')
        origin.update(related_source=name,related_source_sha256=item['sha256'],
            replacement_commit=lock['replacement_commit'],
            scope='Conservative preservation for historical tangent documentation/tests; upstream replaced the Go algorithm with musl')
        selected.append(('Go-BSD-3-Clause-LICENSE.txt',data,origin))
    return selected


def runtime_math_materials(sdk,sources):
    """Retain historical per-file terms for byte-pinned math ports conservatively."""
    if not sources:return []
    folder=HERE/'licenses/data-references/musl-math'
    lock=json.loads(audit.bounded(folder/'sources.json',65536))
    if lock.get('kind')!='pinned-musl-math-notice-references' or lock.get('approved') is not False:
        raise ValueError('Invalid math notice reference lock')
    references={}
    for name,item in sorted(sources.items()):
        prefix=verified_source_prefix(sdk[name],item)
        selected=lock['sources'].get(name)
        if selected is None:
            if b'Ported from musl' in prefix:raise ValueError('Unreviewed musl math port')
            continue
        if (selected['sha256'],selected['size'])!=(item['sha256'],item['size']):
            raise ValueError('Math port differs from reviewed SDK source')
        for path in selected['references']:
            if not re.fullmatch(r'src/math/[A-Za-z0-9_]+\.c',path):raise ValueError('Unsafe math reference path')
            references.setdefault(path,[]).append(dict(path=name,sha256=item['sha256']))
    if not references:return []
    def material(item):
        filename=item['file']
        if (not isinstance(filename,str) or Path(filename).name!=filename or '/' in filename
                or '\\' in filename or ':' in filename or not filename.endswith('.gz')
                or type(item['size']) is not int or not 0<item['size']<=65536):
            raise ValueError('Unsafe or excessive math reference material')
        compressed=audit.bounded(folder/filename,65536)
        with gzip.GzipFile(fileobj=io.BytesIO(compressed)) as stream:data=stream.read(65537)
        if len(data)!=item['size'] or hashlib.sha256(data).hexdigest()!=item['sha256']:
            raise ValueError('Pinned math reference changed')
        return data
    archive=lock['archive']
    root=material(lock['copyright'])
    materials=[('Musl-math-1.1.18-COPYRIGHT.txt',root,
        dict(kind='historical-math-root-terms',source_url=archive['url'],archive_sha256=archive['sha256'],
            path='COPYRIGHT',source_sha256=lock['copyright']['sha256'],scope=lock['scope']))]
    for path,related in sorted(references.items()):
        item=lock['references'][path];data=material(item);prefix=source_notice_prefix(data)
        if len(prefix)!=item['prefix_bytes'] or hashlib.sha256(prefix).hexdigest()!=item['prefix_sha256']:
            raise ValueError('Math reference prefix differs from reviewed bytes')
        if prefix:
            materials.append(('Musl-math-'+path.rsplit('/',1)[1]+'.txt',prefix,
                dict(kind='historical-math-source-notice',source_url=archive['url'],archive_sha256=archive['sha256'],
                    path=path,source_sha256=item['sha256'],offset=0,length=len(prefix),
                    related_sdk_sources=related,scope=lock['scope'])))
    return materials


def append_header_notices(materials,external,sdk,facts):
    """Preserve every verified SDK header prefix, including explicit empty rows."""
    headers=[]
    for name in sorted(external):
        data=sdk[name]
        if hashlib.sha256(data).hexdigest()!=external[name]:
            raise ValueError('SDK header differs from pinned archive')
        prefix=source_notice_prefix(data)
        headers.append(dict(path=name,source_sha256=external[name],prefix_sha256=hashlib.sha256(prefix).hexdigest(),
                            prefix_bytes=len(prefix),applicability='pending'))
        if prefix:
            filename='SDK-header-'+hashlib.sha256(name.encode()).hexdigest()[:24]+'.txt'
            materials.append((filename,prefix,dict(kind='pinned-sdk-header-prefix',path=name,
                archive_sha256=facts['archive_sha256'],source_sha256=external[name],offset=0,length=len(prefix))))
    return headers


def graphviz_source_materials(dependencies,archive,lock):
    """Recheck observed upstream source bytes and preserve per-file comments."""
    if builder.digest(archive)!=lock['sha256']:
        raise ValueError('Graphviz archive differs from pinned source')
    entries={}
    for item in dependencies:
        if item.get('origin')!='source':continue
        name=item.get('path');path=PurePosixPath(name) if isinstance(name,str) else None
        size=item.get('size')
        if (not name or '\\' in name or '\0' in name or path.is_absolute() or '..' in path.parts
                or path.as_posix()!=name or name in entries or len(name)>4096
                or not re.fullmatch(r'[0-9a-f]{64}',item.get('sha256',''))
                or type(size) is not int or not 0<=size<=1024**2):
            raise ValueError('Invalid or duplicate Graphviz source record')
        entries[name]=item
        if len(entries)>5000:raise ValueError('Too many Graphviz source records')
    if not entries or sum(item['size'] for item in entries.values())>64*1024**2:
        raise ValueError('Missing or excessive Graphviz source records')
    sources=archive_files(archive,'graphviz-16.1.0',set(entries))
    rows=[];materials=[]
    for name,item in sorted(entries.items()):
        data=sources[name]
        if len(data)!=item['size'] or hashlib.sha256(data).hexdigest()!=item['sha256']:
            raise ValueError('Graphviz source differs from pinned archive')
        prefix=source_notice_prefix(data)
        later=[];offset=0
        for number,line in enumerate(data.splitlines(keepends=True),1):
            if offset>=len(prefix) and re.search(rb'copyright|SPDX-License-Identifier|licen[cs]e|public domain',line,re.IGNORECASE):
                if len(later)>=256 or len(line)>4096:
                    raise ValueError('Graphviz source indicators exceed review limit')
                later.append(dict(line=number,offset=offset,text=line.decode('utf-8').rstrip('\r\n')))
            offset+=len(line)
        rows.append(dict(path=name,source_sha256=item['sha256'],size=len(data),
            prefix_sha256=hashlib.sha256(prefix).hexdigest(),prefix_bytes=len(prefix),applicability='pending',
            later_license_indicators=later))
        if prefix:
            filename='Graphviz-source-'+hashlib.sha256(name.encode()).hexdigest()[:24]+'.txt'
            materials.append((filename,prefix,dict(kind='pinned-graphviz-source-prefix',path=name,
                archive_sha256=lock['sha256'],source_sha256=item['sha256'],offset=0,length=len(prefix))))
        if later:
            filename='Graphviz-source-reference-'+hashlib.sha256(name.encode()).hexdigest()[:24]+'.txt'
            materials.append((filename,data,dict(kind='pinned-graphviz-source-additional-reference',path=name,
                archive_sha256=lock['sha256'],source_sha256=item['sha256'],offset=0,length=len(data),
                scope='Full source for review of later license-related text; indicator matches are not license decisions')))
    return rows,materials


def archive_files(path,prefix,names):
    found={};count=expanded=0
    with tarfile.open(path) as archive:
        for member in archive:
            count+=1;expanded+=member.size
            if count>50000 or expanded>1024**3:raise ValueError('Archive exceeds notice preparation limits')
            parts=PurePosixPath(member.name)
            if parts.is_absolute() or '..' in parts.parts or parts.parts[0]!=prefix:raise ValueError('Unexpected archive path')
            relative=PurePosixPath(*parts.parts[1:]).as_posix()
            if relative not in names:continue
            if relative in found or not member.isfile() or member.size>1024**2:raise ValueError('Invalid or excessive notice/header entry')
            found[relative]=archive.extractfile(member).read(1024**2+1)
    if set(found)!=set(names):raise ValueError('Required notice/header absent from archive')
    return found


