def license_material(name):
    item=json.loads(audit.bounded(HERE/'licenses/material-source-lock.json',65536))[name]
    filename=Path(item['file'])
    if filename.name!=str(filename):raise ValueError('License material must be a local filename')
    data=audit.bounded(HERE/'licenses'/filename,65536)
    if len(data)!=item['size'] or hashlib.sha256(data).hexdigest()!=item['sha256']:
        raise ValueError('Pinned canonical license text changed')
    return data,dict(kind='pinned-canonical-license-text',source_url=item['url'],source_sha256=item['sha256'])


def sdk_archive_identity(facts):
    nested=facts.get('archive',{})
    if not isinstance(nested,dict):raise ValueError('Invalid SDK archive identity')
    url=nested.get('url',facts.get('archive_url'))
    sha=nested.get('sha256',facts.get('archive_sha256'))
    if (not isinstance(url,str) or not url.startswith('https://')
            or not isinstance(sha,str) or not re.fullmatch(r'[0-9a-f]{64}',sha)
            or ('archive_url' in facts and facts['archive_url']!=url)
            or ('archive_sha256' in facts and facts['archive_sha256']!=sha)):
        raise ValueError('Missing or conflicting pinned SDK archive identity')
    return dict(url=url,sha256=sha)


def flex_scanner_notice(data,generator,*,apple=False):
    expected_version='flex 2.6.4 Apple(flex-35)' if apple else 'flex 2.6.4'
    if (b'A lexical scanner generated by flex' not in data[:65536]
            or generator.get('version')!=expected_version
            or not re.fullmatch(r'[0-9a-f]{64}',generator.get('sha256',''))):
        raise ValueError('Expected recorded Flex 2.6.4 generator and scanner')
    for macro,value in (('MAJOR',2),('MINOR',6),('SUBMINOR',4)):
        matches=re.findall(rb'^\s*#define\s+YY_FLEX_'+macro.encode()+rb'_VERSION\s+(\d+)\s*$',data,re.MULTILINE)
        if matches!=[str(value).encode()]:raise ValueError('Generated scanner version differs from recorded Flex')
    key='flex_apple_35_copying' if apple else 'flex_2_6_4_copying'
    lock=json.loads(audit.bounded(HERE/'licenses/material-source-lock.json',65536))[key]
    license_bytes=audit.bounded(HERE/'licenses'/lock['file'],65536)
    if len(license_bytes)!=lock['size'] or hashlib.sha256(license_bytes).hexdigest()!=lock['sha256']:
        raise ValueError('Pinned Flex license material changed')
    return license_bytes,dict(kind='pinned-generator-license-material',source_url=lock['url'],
        source_sha256=lock['sha256'],generator_version='2.6.4',generator_sha256=generator['sha256'],
        qualification='Recorded generator/scanner versions agree; preserves upstream generated-scanner exception, no bundle approval')


def color_notice(data):
    lines=[]
    for line in data.splitlines(keepends=True):
        if line.strip() and not line.startswith(b'#'):break
        lines.append(line)
    prefix=b''.join(lines)
    if len(prefix)>65536 or not all(token in prefix for token in (b'Apache-Style Software License for ColorBrewer',b'Copyright',b'THIS SOFTWARE IS PROVIDED')):
        raise ValueError('ColorBrewer notice is missing or incomplete')
    return prefix


def color_acknowledgment(data):
    notice=color_notice(data)
    words=b' '.join(line.lstrip(b'# \t').strip() for line in notice.splitlines())
    acknowledgment=(b'This product includes color specifications and designs developed '
                    b'by Cynthia Brewer (http://colorbrewer.org/).')
    if acknowledgment not in words:raise ValueError('Required ColorBrewer acknowledgment differs from source')
    return acknowledgment+b'\n'


def bison_notice(data):
    data=data[:65536]
    if not data.startswith(b'/* A Bison parser, made by GNU Bison '):
        raise ValueError('Expected generated Bison prefix')
    end=0
    while match:=re.match(rb'\s*/\*.*?\*/',data[end:],re.DOTALL):
        end+=match.end()
        comment=match.group()
        if b'As a special exception' in comment and b'version 2.2 of Bison.' in comment:
            if b'Copyright' not in data[:end] or b'GNU General Public License' not in data[:end]:break
            return data[:end]
    raise ValueError('Complete Bison license and exception not found')


def source_notice_prefix(data):
    end=0
    while True:
        start=end+re.match(rb'\s*',data[end:]).end()
        if data[start:start+2]==b'/*':
            stop=data.find(b'*/',start+2)
            if stop<0:raise ValueError('Unterminated leading source comment')
            end=stop+2
        elif data[start:start+2]==b'//':
            stop=data.find(b'\n',start+2);end=len(data) if stop<0 else stop+1
        else:
            if end:end=start
            break
        if end>65536:raise ValueError('Leading source notice exceeds limit')
    if end>65536:raise ValueError('Leading source notice exceeds limit')
    return data[:end]


def object_notice_sources(record,linked_build,evidence,kind,prefixes,*,artifacts=('linux-musl-x86_64',)):
    if evidence is None:return {},None
    data=json.loads(audit.bounded(evidence,8*1024**2))
    facts=record['sdk']['facts']
    sdk_sha=facts.get('archive_sha256',facts.get('archive',{}).get('sha256'))
    if (not isinstance(sdk_sha,str) or not re.fullmatch(r'[0-9a-f]{64}',sdk_sha)
            or record['artifact_id'] not in artifacts
            or (record['artifact_id'] in ('linux-glibc-aarch64','linux-musl-aarch64') and data.get('artifact_id')!=record['artifact_id'])
            or data.get('kind')!=kind
            or data.get('provenance_sha256')!=builder.digest(linked_build/'provenance.json')
            or data.get('executable_sha256')!=record['executable_sha256']
            or data.get('sdk_archive_sha256')!=sdk_sha):
        raise ValueError('Object evidence does not match this build and SDK')
    entries=data.get('sources')
    if not isinstance(entries,list) or not 0<len(entries)<=5000:raise ValueError('Invalid source evidence count')
    sources={}
    for item in entries:
        name=item['path'];path=PurePosixPath(name)
        if (not name.startswith(prefixes) or '..' in path.parts or path.as_posix()!=name
                or name in sources or not re.fullmatch(r'[0-9a-f]{64}',item.get('sha256',''))):
            raise ValueError('Invalid or duplicate source evidence')
        sources[name]=item
    return sources,builder.digest(evidence)


